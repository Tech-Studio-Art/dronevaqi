"""Small helpers to write OpenFOAM (v1912, ESI) case dictionaries from Python."""
import os
import subprocess

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by sim/cfd -- Drone V AQI (Tech Studio .Art)
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""

ENV = dict(os.environ, WM_PROJECT_DIR="/usr/share/openfoam", OMPI_ALLOW_RUN_AS_ROOT="1",
           OMPI_ALLOW_RUN_AS_ROOT_CONFIRM="1", OMPI_MCA_rmaps_base_oversubscribe="1")


def write(case, rel, body, cls="dictionary"):
    path = os.path.join(case, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(HEADER.format(cls=cls, obj=os.path.basename(rel)))
        f.write(body)


def run(case, cmd, log=None):
    log = log or cmd.split()[0]
    with open(os.path.join(case, f"log.{log}"), "w") as f:
        r = subprocess.run(cmd, shell=True, cwd=case, env=ENV, stdout=f, stderr=subprocess.STDOUT)
    if r.returncode != 0:
        raise RuntimeError(f"{cmd} failed in {case}; see log.{log}")


def vec(v):
    return "(" + " ".join(f"{x:.6g}" for x in v) + ")"


def field(name, cls, dim, internal, patches):
    """patches: dict patchName -> body string."""
    pb = "\n".join(f"    {p}\n    {{\n{b}\n    }}" for p, b in patches.items())
    return name, cls, f"""
dimensions      {dim};
internalField   uniform {internal};
boundaryField
{{
{pb}
}}
"""


def write_field(case, t, spec):
    name, cls, body = spec
    write(case, f"{t}/{name}", body, cls=cls)


def last_time(case):
    ts = []
    for d in os.listdir(case):
        try:
            ts.append((float(d), d))
        except ValueError:
            pass
    return max(ts)[1]


def read_dat(path):
    """Read last line of an OpenFOAM functionObject .dat file -> list of floats."""
    rows = [l for l in open(path) if l.strip() and not l.startswith("#")]
    return [float(x) for x in rows[-1].replace("(", " ").replace(")", " ").split()]


def vtk_zone(case, zone=None, name="VTK", fields=("U", "T")):
    """Export latest time (whole mesh or one cellZone) to VTK and return pyvista grid
    with cell volumes. Note: this OpenFOAM build (Debian v1912) crashes on ANY
    runtime functionObject (SHA1 digest bug), so all post-processing is done here."""
    import pyvista as pv
    import glob
    opt = f"-cellZone {zone}" if zone else ""
    run(case, f"foamToVTK -latestTime -poly-decomp -no-point-data -no-boundary -overwrite -name {name} {opt} "
              f"-fields '({' '.join(fields)})'", f"vtk.{name}")
    f = sorted(glob.glob(os.path.join(case, name, "*", "internal.vtu")))[-1]
    g = pv.read(f)
    g = g.compute_cell_sizes(length=False, area=False, volume=True)
    return g


def zone_stats(g):
    import numpy as np
    V = np.asarray(g.cell_data["Volume"])
    out = {"V": float(V.sum())}
    for k in g.cell_data.keys():
        a = np.asarray(g.cell_data[k])
        if k == "Volume":
            continue
        out[k + "_int"] = (a.T * V).T.sum(axis=0) if a.ndim > 1 else float((a * V).sum())
        out[k + "_avg"] = out[k + "_int"] / V.sum()
    return out
