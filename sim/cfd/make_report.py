#!/usr/bin/env python3
"""Build REPORT.md from the JSON results (numbers are never typed by hand)."""
import glob
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "runs")


def J(p):
    p = os.path.join(R, p)
    return json.load(open(p)) if os.path.exists(p) else None


def f(x, n=1):
    return f"{x:,.{n}f}"


drones = J("drone3d/summary.json") or []
d = {r["case"]: r for r in drones}
mix = {os.path.basename(os.path.dirname(p)): json.load(open(p))
       for p in glob.glob(os.path.join(R, "mixing", "*", "result.json"))}
twod = {}
for p in glob.glob(os.path.join(R, "2d", "summary_*.json")):
    for r in json.load(open(p)):
        twod[r["case"]] = r
s3d = J("shelter3d/summary.json") or []
if mix:
    json.dump(mix, open(os.path.join(R, "mixing", "summary.json"), "w"), indent=1)
m0 = J("models0d.json")

L = []
A = L.append
A("# Drone V AQI – CFD & pollution-model results\n")
A("*Tech Studio .Art · Delhi post-Diwali / stubble-burning episode · ambient PM2.5 = 300 µg/m³, "
  "PM10 = 500 µg/m³ (PM10 > PM2.5, as in Delhi's November episodes).*\n")
A("All numbers in this report are generated by `make_report.py` from the simulation outputs in "
  "`runs/`. Methods are standard ones from the literature (cited per section); no new pollution "
  "model was invented. Every model has limits, listed at the end of each section.\n")

# ---------------------------------------------------------------- headline
A("## Headline\n")
hv = d.get("heavy_above", {})
A("| Solution | What was simulated | Best local effect | Scale it acts on | Verdict |")
A("|---|---|---|---|---|")
if hv:
    A(f"| Filter drones (reference) | 3-D CFD, 2 kg quad & 50 kg heavy-lift, ducted filter above/below rotors | "
      f"100 heavy drones over 500 × 500 m: ≤ 1.5 % PM2.5, ≤ 7.7 % PM10 (calm, 30 m layer) | 25 ha | Not viable |")
if "heavy_z60" in mix:
    s = mix["heavy_z60"]["series"]
    red = 100 * (1 - s[-1]["z<2m"] / s[0]["z<2m"])
    A(f"| 1. Drones as inversion mixers | Axisymmetric unit-cell URANS, stratified (Boussinesq) | "
      f"{f(red)} % lower breathing-zone PM after 30 min (100 heavy drones @ 60 m, 25 ha) | 25 ha per 100 drones | "
      f"Most promising drone use; needs field trial |")
sh_best = max((r for r in s3d if "error" not in r), key=lambda r: r["reduction_pct"], default=None)
if s3d:
    par = [r for r in s3d if r.get("wind") == "parallel" and "error" not in r]
    lo = min(r["reduction_pct"] for r in par) if par else float("nan")
    hi = max(r["reduction_pct"] for r in s3d if "error" not in r)
    A(f"| 2. Clean-air shower (bus shelter) | 2-D and 3-D RANS | {f(lo, 0)}–{f(hi, 0)} % in the breathing zone | one shelter | "
      f"Works; the cheapest real protection |")
es = twod.get("espfence_U1.0_PM25")
if es:
    A(f"| 3a. Electrostatic wind fence | 2-D RANS, Deutsch–Anderson sink | {f(100 * (1 - es['pedestrian_C']['x=2m']), 0)} % PM2.5 "
      f"at 2 m, {f(100 * (1 - es['pedestrian_C']['x=40m']), 0)} % at 40 m downwind | road corridor | Promising, pilot it |")
if m0:
    cor = m0["vehicles"]["corridor"][-1]
    A(f"| 3b. Ram-air filters on buses | Bernoulli + filter model, road box | {f(cor['PM25_reduction_pct'], 2)} % PM2.5 "
      f"with {cor['buses_on_1km']} buses per km | road | Not viable for outdoor air |")
fg = twod.get("fognet_U2.0")
if fg:
    A(f"| 4a. Fog-harvesting nets | 2-D RANS, Rivera (2011) mesh model | {f(100 * (1 - fg['pedestrian_PM_C']['x=10m']), 1)} % PM "
      f"10 m downwind; {f(fg['water_L_m2_day'], 1)} L water /m²/day | rooftop | Negligible for PM |")
if m0:
    co = m0["coagulation"]["runs"][-1]
    A(f"| 4b. Bipolar-ion agglomeration | Smoluchowski + Fuchs electrostatic kernel | median size 0.47 → "
      f"{f(co['6h']['MMD_um'], 2)} µm in 6 h; mass > 2.5 µm stays {f(co['6h']['mass_above_2p5um_pct'], 1)} % | — | Does not work |")
    jb = [r for r in m0["charged_mist"]["junction_box"] if r["mode"].startswith("charged drop +") and r["water_L_per_h"] == 5000]
    if jb:
        A(f"| 4c. Charged mist at a junction | Slinn + Coulomb collection, box | {f(jb[0]['PM25_red_pct'], 0)} % PM2.5 with "
          f"5,000 L/h over 50 × 50 m | junction | Local hotspot tool only |")
A("")

# ---------------------------------------------------------------- drones
A("## 0. Filter drones – 3-D CFD (reference case)\n")
A("**Method.** OpenFOAM v1912, steady RANS (k-ω SST, Menter 1994). Rotors = uniformly loaded actuator "
  "disks with prescribed thrust (Froude–Rankine momentum theory as a momentum source). Filter = Darcy "
  "porous zone with the Davies (1973) fibrous-media coefficient (charged electret media, d_f = 20 µm, "
  "solidity 3 %, 3 mm, pleated to 5× disk area), housed in a duct around each rotor. PM = passive scalar "
  "(Sc_t = 0.7, Tominaga & Stathopoulos 2007) with a first-order capture sink whose single-pass "
  "efficiency comes from single-fibre filtration theory (Hinds 1999) at the CFD face velocity. "
  "Disk thrust is iterated so net lift (thrust − aerodynamic load on the filter) = weight.\n")
A("| Case | Weight (N) | Disk thrust (N) | Filter Δp (Pa) | Hover power (W) | Flight time (min) | Rotor flow (m³/s) | CADR PM2.5 (m³/s) | CADR PM10 (m³/s) | PM2.5 removed (g/h) |")
A("|---|---|---|---|---|---|---|---|---|---|")
for k in ("quad_none", "quad_above", "quad_below", "heavy_none", "heavy_above", "heavy_below"):
    r = d.get(k)
    if not r:
        continue
    A(f"| {k.replace('_', ' / ')} | {f(r['weight_N'], 0)} | {f(r.get('thrust_converged_N', r['weight_N']), 0)} | "
      f"{f(r.get('dp_Pa', 0), 0)} | {f(r['power_mt_W'], 0)} | {f(r['endurance_mt_min'], 1)} | {f(r['Q_rotor'], 1)} | "
      f"{f(r.get('CADR_PM25', 0), 2)} | {f(r.get('CADR_PM10', 0), 2)} | {f(r.get('g_per_h_PM25', 0), 2)} |")
A("\n![quad](figures/drone3d_quad.png)\n![heavy](figures/drone3d_heavy.png)\n")
A("**What the CFD shows**")
A("- The filter's pressure drop (40–60 Pa) is comparable to the rotor disk loading (≈ 80–100 Pa). The air "
  "pushes the filter down with a force of 45–55 % of the drone's weight, so the rotors must make 1.5× the "
  "thrust and about 2× the power. Flight time roughly halves.")
A("- Single-pass capture is ~98 % for coarse PM (2.5–10 µm) but only ~12 % for PM2.5. Delhi's winter PM2.5 is "
  "mostly 0.1–1 µm smoke, which slips through any media open enough for a rotor to breathe through.")
A("- Above vs below makes little difference to cleaning. A filter **below** spreads the downwash into a wide, "
  "slow plume (less road-dust lift-off near the ground); a filter **above** keeps a narrow jet.")
A("- Electrostatic charge on the media is included; at rotor face velocities (~1 m/s through the pleats) it "
  "adds little for 0.1–1 µm particles.\n")
A("**Fleet scale (box model with the CFD CADRs, 10 min battery-swap per sortie, 500 × 500 m zone):** "
  "100 heavy drones give ≤ 1.5 % PM2.5 and ≤ 7.7 % PM10 reduction in calm air (0.3 m/s) with a 30 m polluted layer, "
  "falling to 0.2 % / 1 % with a 100 m layer and 1 m/s wind. They draw ~0.7 MW on average.\n")
A("*Limits:* steady RANS, no swirl, rotors lumped as disks, duct modelled as an impermeable porous ring, "
  "hover out of ground effect.\n")

# ---------------------------------------------------------------- mixing
A("## 1. Drones as inversion mixers\n")
A("**Method.** buoyantBoussinesqPimpleFoam (transient URANS, Boussinesq buoyancy, standard k-ε). "
  "Night-time inversion: potential temperature +5 K over the lowest 100 m, neutral above. PM falls "
  "linearly from the surface value to 50 % at 100 m (cleaner residual layer aloft). 100 drones on a 50 m grid "
  "over 500 × 500 m are represented by one axisymmetric unit cell (R = 28.2 m, symmetry outer wall), the "
  "standard periodic-array treatment. Each drone = actuator disk with thrust = weight. PM is carried exactly by "
  "the potential-temperature field (same transport equation, Sc_t = Pr_t = 0.7; a linear θ–PM relation is "
  "preserved). Analytic check: max penetration of a momentum jet into linear stratification "
  "≈ 2.9 M^¼ N^-½ (Turner 1966; List 1982).\n")
A("| Case | Hover height (m) | Jet penetration, theory (m) | Breathing-zone (0–2 m) PM after 30 min | Reduction |")
A("|---|---|---|---|---|")
lab = {"no_drone": "no drones", "quad_z30": "100 quads", "heavy_z60": "100 heavy", "heavy_z90": "100 heavy"}
for k in ("no_drone", "quad_z30", "heavy_z60", "heavy_z90"):
    r = mix.get(k)
    if not r:
        continue
    s = r["series"]
    A(f"| {lab[k]} | {f(r['hover_z'], 0) if r['thrust_N'] else '–'} | {f(r['jet_penetration_theory_m'], 0) if r['thrust_N'] else '–'} | "
      f"{f(100 * s[-1]['z<2m'], 1)} % of initial surface PM (start {f(100 * s[0]['z<2m'], 1)} %) | "
      f"**{f(100 * (1 - s[-1]['z<2m'] / s[0]['z<2m']), 1)} %** |")
A("\n![mixing](figures/mixing_timeseries.png)\n![mixing field](figures/mixing_field_heavy_z60.png)\n")
A("**Reading it.** Heavy drones hovering inside the inversion pull cleaner air down from aloft and stir the "
  "stagnant surface layer. The maximum possible gain is set by how much cleaner the air aloft is (here: "
  "full mixing of 0–100 m gives 25 %). Hovering at 60 m acts within 5–10 min; at 90 m the drones "
  "draw the cleanest air but their jets need ~15 min to reach the ground. With wind exchanging the zone's air every 500 m / U, the steady "
  "benefit is roughly the 30-min value × τ_adv/(τ_adv + τ_mix): about 3/4 of it at 0.3 m/s, about half at 1 m/s.\n")
A("**Energy.** Theoretical minimum to erase a 5 K / 100 m inversion is ≈ 180 J/m² (12 kWh for 25 ha). "
  "100 heavy drones draw ≈ 0.68 MW while airborne (≈ 150 airframes to keep 100 flying), i.e. ~5 MWh per "
  "8-h night for 25 ha, comparable to orchard frost fans (≈ 75 kW per 4–5 ha). Ground-mounted "
  "mixing fans/towers would do the same job without batteries or flight risk; drones remain best for "
  "*measuring* the profile and deciding when mixing helps.\n")
A("*Limits:* standard k-ε has no buoyancy damping of turbulence, so mixing is over-predicted (upper bound). "
  "No wind in the unit cell; PM10 settling (~9 m per 30 min) neglected; if a stubble-smoke layer sits aloft "
  "(PM aloft ≥ surface) mixing makes the surface worse – always profile first.\n")

# ---------------------------------------------------------------- shelter
A("## 2. Clean-air shower at a bus shelter\n")
A("**Method.** Steady RANS k-ε with Richards & Hoxey (1993) atmospheric-boundary-layer inlet and rough-wall "
  "functions (COST 732 / AIJ guidelines). Shelter 8 m × 2.5 m, roof 2.5 m, back wall, open ends. Filtered air "
  "(5 % of ambient PM) is blown down from a 7 m × 2 m roof outlet. Breathing zone = 0.5–1.8 m inside the "
  "shelter. Blower power = flow × 350 Pa (HEPA-class filter + ducting) / 0.5.\n")
if s3d:
    A("**3-D (open ends)**\n")
    A("| Wind (m/s @10 m) | Wind direction | Supply velocity (m/s) | Supply flow (m³/s) | Breathing-zone PM reduction | Blower power (kW) |")
    A("|---|---|---|---|---|---|")
    for r in s3d:
        if "error" in r:
            continue
        A(f"| {r['Uref']} | {'along shelter, through open ends' if r['wind'] == 'parallel' else 'into open front'} | "
          f"{r['w_supply']} | {f(r['Q_m3s'], 1)} | **{f(r['reduction_pct'], 0)} %** | {f(r['fan_kW'], 1)} |")
