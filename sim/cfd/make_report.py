    A("\nJunction box (50 × 50 m, 10 m layer, 1 m/s wind):\n")
    A("| Mode | Water (L/h) | PM2.5 reduction | PM10 reduction |")
    A("|---|---|---|---|")
    for r in m0["charged_mist"]["junction_box"]:
        A(f"| {r['mode']} | {r['water_L_per_h']:,} | {f(r['PM25_red_pct'], 1)} % | {f(r['PM10_red_pct'], 1)} % |")
